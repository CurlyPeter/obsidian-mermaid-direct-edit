import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync } from "fs";

// The version that is actually bundled, read from the installed package, not the range.
const mermaidVersion = JSON.parse(readFileSync("node_modules/mermaid/package.json", "utf8")).version;

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
mermaid-direct-edit: bundles a pinned Mermaid release (see package.json).
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["main.ts"],
	bundle: true,
	// Runs on the phone too: nothing here may import Node builtins or electron.
	external: ["obsidian", ...builtins],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
	legalComments: "eof",  // keeps the bundled libraries' licence notices (MIT and others)
	outfile: "main.js",
	platform: "browser",
	define: { __MERMAID_VERSION__: JSON.stringify(mermaidVersion) },
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
